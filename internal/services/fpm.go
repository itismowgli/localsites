package services

import (
	"fmt"
	"sort"
	"strings"
)

// PHPDefaults mirror MAMP PRO's php.ini so projects moved from MAMP behave the same
// (post_max_size is raised from 8M to match the 32M upload limit).
// output_buffering matters most: old code calling header() after output relies on it.
var PHPDefaults = map[string]string{
	"output_buffering":    "4096",
	"display_errors":      "Off",
	"error_reporting":     "E_ALL",
	"memory_limit":        "128M",
	"upload_max_filesize": "32M",
	"post_max_size":       "32M",
	"max_execution_time":  "30",
	"max_input_time":      "60",
	"short_open_tag":      "Off",
}

// FPMPool is one site's PHP worker pool.
type FPMPool struct {
	Name        string // site folder (pool name)
	Socket      string
	ErrorLog    string
	MySQLSocket string
	TmpDir      string
	Overrides   map[string]string
	Admin       map[string]string // php_admin_value lines (system-level settings such as sendmail_path)
}

// FPMConfig renders a php-fpm.conf for one PHP version with one pool per site.
func FPMConfig(version, errorLog string, pools []FPMPool) string {
	var b strings.Builder
	fmt.Fprintf(&b, "; Generated by LocalSites for PHP %s. Do not edit.\n[global]\nerror_log = %q\ndaemonize = no\n", version, errorLog)
	for _, p := range pools {
		fmt.Fprintf(&b, `
[%s]
listen = %q
listen.mode = 0600
pm = ondemand
pm.max_children = 8
pm.process_idle_timeout = 10s
catch_workers_output = yes
decorate_workers_output = no
clear_env = yes
env[PATH] = /usr/local/bin:/opt/homebrew/bin:/usr/bin:/bin
env[TMPDIR] = %q
php_admin_value[pdo_mysql.default_socket] = %q
php_admin_value[mysqli.default_socket] = %q
php_admin_value[error_log] = %q
php_admin_flag[log_errors] = on
php_admin_value[sys_temp_dir] = %q
php_admin_value[upload_tmp_dir] = %q
`, p.Name, p.Socket, p.TmpDir, p.MySQLSocket, p.MySQLSocket, p.ErrorLog, p.TmpDir, p.TmpDir)
		vals := map[string]string{}
		for k, v := range PHPDefaults {
			vals[k] = v
		}
		for k, v := range p.Overrides {
			vals[k] = v
		}
		keys := make([]string, 0, len(vals))
		for k := range vals {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			fmt.Fprintf(&b, "php_value[%s] = %s\n", k, vals[k])
		}
		admin := make([]string, 0, len(p.Admin))
		for k := range p.Admin {
			admin = append(admin, k)
		}
		sort.Strings(admin)
		for _, k := range admin {
			fmt.Fprintf(&b, "php_admin_value[%s] = %q\n", k, p.Admin[k])
		}
	}
	return b.String()
}
