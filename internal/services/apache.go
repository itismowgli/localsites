package services

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// ApacheSite is what the Apache config needs to know about a site.
type ApacheSite struct {
	Folder  string
	Domain  string
	Path    string // project folder
	Docroot string // absolute web root
	FPMSock string
	LogBase string // <logs>/sites/<folder>
}

// ApacheConfig renders httpd.conf. Apache listens only on 127.0.0.1 with TLS; the front door
// (Valet's nginx or LocalSites' built-in proxy) terminates browser HTTPS and forwards here.
type ApacheConfig struct {
	Port        int
	ModulesDir  string
	MimeTypes   string
	ServerRoot  string
	RunDir      string
	LogDir      string
	CertFile    string
	KeyFile     string
	DefaultRoot string
	Sites       []ApacheSite
}

var apacheModules = []string{
	"mpm_event", "authn_core", "authz_core", "authz_host", "authz_user", "access_compat", "auth_basic",
	"authn_file", "mime", "log_config", "env", "headers", "setenvif", "version", "unixd", "dir", "alias",
	"rewrite", "expires", "deflate", "filter", "socache_shmcb", "ssl", "proxy", "proxy_fcgi", "remoteip",
	"include", "negotiation", "autoindex",
}

func (c ApacheConfig) Render() string {
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f, a...) }
	w("# Generated by LocalSites. Do not edit: it is rewritten on every change.\n")
	w("ServerRoot %q\nListen 127.0.0.1:%d\nPidFile %q\nServerName localhost\n", c.ServerRoot, c.Port, filepath.Join(c.RunDir, "httpd.pid"))
	for _, m := range apacheModules {
		if p := filepath.Join(c.ModulesDir, "mod_"+m+".so"); fileExists(p) {
			w("LoadModule %s_module %q\n", m, p)
		}
	}
	w(`TypesConfig %q
ErrorLog %q
LogLevel warn ssl:error
LogFormat "%%a %%l %%u %%t \"%%r\" %%>s %%b \"%%{Referer}i\" \"%%{User-Agent}i\" %%D" combined
DefaultRuntimeDir %q
Mutex file:%s default
ServerTokens Prod
TraceEnable Off
Timeout 300
KeepAlive On
# Small for local work: one process with a few threads, grows when needed
StartServers 1
ServerLimit 4
ThreadsPerChild 16
MinSpareThreads 4
MaxSpareThreads 16
MaxRequestWorkers 64
DirectoryIndex index.php index.html index.htm
AddDefaultCharset Off

# Real client address from the front door
RemoteIPHeader X-Real-IP
RemoteIPInternalProxy 127.0.0.1

SSLEngine on
SSLCertificateFile %q
SSLCertificateKeyFile %q
SSLSessionCache "shmcb:%s(512000)"
SSLProtocol -all +TLSv1.2 +TLSv1.3

<Directory />
    AllowOverride None
    Require all denied
</Directory>
<FilesMatch "^\.(ht|env|git)">
    Require all denied
</FilesMatch>

<VirtualHost 127.0.0.1:%d>
    ServerName localsites-default
    Header always set X-LocalSites-Default "1"
    DocumentRoot %q
    <Directory %q>
        Require all granted
    </Directory>
</VirtualHost>
`, c.MimeTypes, filepath.Join(c.LogDir, "apache-error.log"), c.RunDir, c.RunDir, c.CertFile, c.KeyFile,
		filepath.Join(c.RunDir, "ssl_scache"), c.Port, c.DefaultRoot, c.DefaultRoot)

	for _, s := range c.Sites {
		w(`
# %s
<VirtualHost 127.0.0.1:%d>
    ServerName %s
    ServerAlias www.%s
    DocumentRoot %q
    ErrorLog %q
    CustomLog %q combined
    <Directory %q>
        Options FollowSymLinks
        AllowOverride All
        Require all granted
    </Directory>
    <FilesMatch "\.(php|phtml)$">
        SetHandler "proxy:unix:%s|fcgi://%s"
    </FilesMatch>
</VirtualHost>
`, s.Folder, c.Port, s.Domain, s.Domain, s.Docroot, s.LogBase+"-error.log", s.LogBase+"-access.log", s.Path, s.FPMSock, fcgiName(s.Folder))
	}
	return b.String()
}

// fcgiName gives each site its own backend worker name in mod_proxy.
func fcgiName(folder string) string {
	return "site-" + strings.Map(func(r rune) rune {
		if r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '-' {
			return r
		}
		return '-'
	}, folder)
}

// DefaultPage writes the page shown for unknown host names.
func DefaultPage(dir string) error {
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "index.html"), []byte(`<!doctype html><meta charset="utf-8"><title>No site here</title>
<body style="font:16px system-ui;padding:48px;max-width:640px"><h1>No site here</h1>
<p>This address is not switched on in LocalSites. Open the LocalSites app to turn the project on.</p>`), 0o600)
}

func fileExists(p string) bool { _, err := os.Stat(p); return err == nil }
