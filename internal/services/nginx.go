package services

import (
	"fmt"
	"path/filepath"
	"strings"
)

// NginxSite is one PHP project served by nginx instead of Apache.
type NginxSite struct {
	Domain  string
	Docroot string // absolute web root
	FPMSock string
	LogBase string
}

// NginxConfig renders nginx.conf. Like Apache, nginx listens only on 127.0.0.1 (plain HTTP: the front door
// terminates browser HTTPS and forwards here). Each project gets the usual PHP setup: pretty URLs fall
// back to index.php (Laravel, WordPress), dotfiles other than .well-known are refused.
type NginxConfig struct {
	Port      int
	RunDir    string
	LogDir    string
	MimeTypes string // nginx's mime.types
	FastCGI   string // nginx's fastcgi_params
	Sites     []NginxSite
}

func (c NginxConfig) Render() string {
	tmp := filepath.Join(c.RunDir, "nginx")
	var b strings.Builder
	fmt.Fprintf(&b, `# Generated by LocalSites. Do not edit.
worker_processes 1;
daemon off;
pid %q;
error_log %q warn;
events { worker_connections 256; }
http {
    include %q;
    default_type application/octet-stream;
    sendfile on;
    keepalive_timeout 30;
    client_max_body_size 512m;
    access_log off;
    client_body_temp_path %q;
    proxy_temp_path %q;
    fastcgi_temp_path %q;
    uwsgi_temp_path %q;
    scgi_temp_path %q;
    server_tokens off;

    server {
        listen 127.0.0.1:%d default_server;
        return 404;
    }
`, filepath.Join(c.RunDir, "nginx.pid"), filepath.Join(c.LogDir, "nginx-error.log"), c.MimeTypes,
		filepath.Join(tmp, "client"), filepath.Join(tmp, "proxy"), filepath.Join(tmp, "fastcgi"), filepath.Join(tmp, "uwsgi"), filepath.Join(tmp, "scgi"), c.Port)
	for _, s := range c.Sites {
		fmt.Fprintf(&b, `
    server {
        listen 127.0.0.1:%d;
        server_name %s;
        root %q;
        index index.php index.html index.htm;
        access_log %q;
        error_log %q;
        location ~ /\.(?!well-known) { deny all; }
        location / { try_files $uri $uri/ /index.php?$query_string; }
        location ~ \.php$ {
            try_files $uri =404;
            include %q;
            fastcgi_pass unix:%s;
            fastcgi_index index.php;
            fastcgi_param SCRIPT_FILENAME $realpath_root$fastcgi_script_name;
            fastcgi_param DOCUMENT_ROOT $realpath_root;
            fastcgi_param HTTPS on;
            fastcgi_param SERVER_PORT 443;
            fastcgi_read_timeout 600s;
        }
    }
`, c.Port, s.Domain, s.Docroot, s.LogBase+"-access.log", s.LogBase+"-error.log", c.FastCGI, s.FPMSock)
	}
	b.WriteString("}\n")
	return b.String()
}
