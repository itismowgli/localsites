// MySQL is LocalSites' own MySQL 8.4 LTS server.
type MySQL struct {
	Base    string // mysql@8.4 install dir
	DataDir string
	Socket  string
	Port    int
	PIDFile string
	LogFile string
	CnfFile string
}

// SQLMode matches MAMP PRO's MySQL 5.7 (minus NO_AUTO_CREATE_USER, removed in 8.0).
const SQLMode = "ONLY_FULL_GROUP_BY,STRICT_TRANS_TABLES,NO_ZERO_IN_DATE,NO_ZERO_DATE,ERROR_FOR_DIVISION_BY_ZERO,NO_ENGINE_SUBSTITUTION"

func (m MySQL) Bin(name string) string { return filepath.Join(m.Base, "bin", name) }

// lowerCaseTableNames: macOS file systems are case-insensitive; 2 matches MAMP and must be set at init.
func lowerCaseTableNames() string {
	if goruntime.GOOS == "darwin" {
		return "2"
	}
	return "0"
}

// WriteCnf writes my.cnf. Network access is limited to 127.0.0.1; X Protocol and LOAD DATA LOCAL are off.
func (m MySQL) WriteCnf() error {
	cnf := fmt.Sprintf(`# Generated by LocalSites. Do not edit.
[mysqld]
basedir = %q
datadir = %q
socket = %q
port = %d
bind-address = 127.0.0.1
mysqlx = OFF
pid-file = %q
log-error = %q
lower_case_table_names = %s
sql_mode = %s
character-set-server = utf8mb4
collation-server = utf8mb4_0900_ai_ci
local_infile = OFF
skip-name-resolve
max_allowed_packet = 64M
# Sized for local development (production defaults use ~460 MB of memory and ~200 MB of disk on day one).
# Crash safety is unchanged: every commit is still written to disk.
performance_schema = OFF
disable_log_bin
innodb_buffer_pool_size = 64M
innodb_redo_log_capacity = 16M
innodb_log_buffer_size = 8M
innodb_undo_log_truncate = ON
innodb_max_undo_log_size = 16M
innodb_temp_data_file_path = ibtmp1:12M:autoextend:max:256M
temptable_max_ram = 32M
tmp_table_size = 16M
max_heap_table_size = 16M
key_buffer_size = 8M
table_open_cache = 400
table_definition_cache = 400
thread_cache_size = 4
max_connections = 50
`, m.Base, m.DataDir, m.Socket, m.Port, m.PIDFile, m.LogFile, lowerCaseTableNames(), SQLMode)
	return os.WriteFile(m.CnfFile, []byte(cnf), 0o600)
}

// Initialized reports whether the data dir has been set up.
func (m MySQL) Initialized() bool { return fileExists(filepath.Join(m.DataDir, "mysql.ibd")) }

// Initialize creates the data dir. Returns an init file that sets the root password on first start.
func (m MySQL) Initialize(rootPassword string) (initFile string, err error) {
	if err := os.MkdirAll(m.DataDir, 0o700); err != nil {
		return "", err
	}
	out, err := exec.Command(m.Bin("mysqld"), "--defaults-file="+m.CnfFile, "--initialize-insecure").CombinedOutput()
	if err != nil {
		return "", fmt.Errorf("mysqld --initialize: %v: %s", err, tail(string(out), 5))
	}
	// Applied by the server before it accepts any connection, so root is never reachable without a password.
	initFile = filepath.Join(filepath.Dir(m.CnfFile), "mysql-init.sql")
	sqlText := fmt.Sprintf("ALTER USER 'root'@'localhost' IDENTIFIED BY '%s';\n", rootPassword)
	return initFile, os.WriteFile(initFile, []byte(sqlText), 0o600)
}

// Args returns the mysqld command line for the supervisor.
func (m MySQL) Args(initFile string) []string {
	args := []string{"--defaults-file=" + m.CnfFile}
	if initFile != "" {
		args = append(args, "--init-file="+initFile)
	}
	return args
}

// Admin connects as root over the unix socket.
func (m MySQL) Admin(rootPassword string) (*sql.DB, error) {
	cfg := mysql.NewConfig()
	cfg.User, cfg.Passwd, cfg.Net, cfg.Addr = "root", rootPassword, "unix", m.Socket
	cfg.Timeout = 5 * time.Second
	db, err := sql.Open("mysql", cfg.FormatDSN())
	if err != nil {
		return nil, err
	}
	db.SetMaxOpenConns(2)
	return db, nil
}

// WaitReady waits until the server accepts root logins.
func (m MySQL) WaitReady(rootPassword string, timeout time.Duration) error {
	db, err := m.Admin(rootPassword)
	if err != nil {
		return err
	}
	defer db.Close()
	end := time.Now().Add(timeout)
	for {
		ctx, cancel := context.WithTimeout(context.Background(), 2*time.Second)
		err = db.PingContext(ctx)
		cancel()
		if err == nil || time.Now().After(end) {
			return err
		}
		time.Sleep(300 * time.Millisecond)
	}
}

// DBInfo describes a database.
type DBInfo struct {
	Name   string  `json:"name"`
	Tables int     `json:"tables"`
	SizeMB float64 `json:"size_mb"`
	Owner  string  `json:"owner,omitempty"` // LocalSites user created for it
}

var systemDBs = map[string]bool{"mysql": true, "information_schema": true, "performance_schema": true, "sys": true}

// ListDatabases returns user databases with sizes.
func ListDatabases(db *sql.DB) ([]DBInfo, error) {
	rows, err := db.Query(`SELECT s.schema_name, COUNT(t.table_name), COALESCE(SUM(t.data_length + t.index_length), 0)
		FROM information_schema.schemata s LEFT JOIN information_schema.tables t ON t.table_schema = s.schema_name
		GROUP BY s.schema_name ORDER BY s.schema_name`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []DBInfo{}
	for rows.Next() {
		var d DBInfo
		var size float64
		if err := rows.Scan(&d.Name, &d.Tables, &size); err != nil {
			return nil, err
		}
		if systemDBs[d.Name] {
			continue
		}
		d.SizeMB = float64(int(size/1048576*10)) / 10
		out = append(out, d)
	}
	return out, rows.Err()
}

// UserFor is the MySQL user LocalSites creates for a database (max 32 chars).
func UserFor(dbName string) string {
	u := "ls_" + strings.ToLower(dbName)
	if len(u) > 32 {
		u = u[:32]
	}
	return u
}

// CreateDatabase creates a database and a user that can only access that database.
// name must already be validated (letters, digits, underscore).
func CreateDatabase(db *sql.DB, name, user, password string) error {
	stmts := []string{
		fmt.Sprintf("CREATE DATABASE IF NOT EXISTS `%s` CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci", name),
	}
	for _, host := range []string{"localhost", "127.0.0.1"} {
		stmts = append(stmts,
			fmt.Sprintf("CREATE USER IF NOT EXISTS '%s'@'%s' IDENTIFIED BY '%s'", user, host, password),
			fmt.Sprintf("ALTER USER '%s'@'%s' IDENTIFIED BY '%s'", user, host, password),
			fmt.Sprintf("GRANT ALL PRIVILEGES ON `%s`.* TO '%s'@'%s'", name, user, host),
		)
	}
	for _, s := range stmts {
		if _, err := db.Exec(s); err != nil {
			return fmt.Errorf("%s: %w", strings.SplitN(s, " IDENTIFIED", 2)[0], err)
		}
	}
	return nil
}

// Backup writes a compressed dump of one database and returns the file path.
func (m MySQL) Backup(rootPassword, name, dir string) (string, error) {
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return "", err
	}
	stamp := time.Now().Format("20060102-150405")
	file := filepath.Join(dir, fmt.Sprintf("%s-%s.sql.gz", name, stamp))
	f, err := os.OpenFile(file, os.O_CREATE|os.O_WRONLY|os.O_EXCL, 0o600)
	for i := 2; errors.Is(err, os.ErrExist) && i < 100; i++ { // two backups in the same second
		file = filepath.Join(dir, fmt.Sprintf("%s-%s-%d.sql.gz", name, stamp, i))
		f, err = os.OpenFile(file, os.O_CREATE|os.O_WRONLY|os.O_EXCL, 0o600)
	}
	if err != nil {
		return "", err
	}
	defer f.Close()
	gz := gzip.NewWriter(f)
	cmd := exec.Command(m.Bin("mysqldump"), "--socket="+m.Socket, "--user=root",
		"--single-transaction", "--routines", "--triggers", "--events", "--hex-blob", "--default-character-set=utf8mb4",
		"--set-gtid-purged=OFF", "--databases", name)
	cmd.Env = append(os.Environ(), "MYSQL_PWD="+rootPassword) // not visible in ps (unlike -p)
	cmd.Stdout = gz
	var stderr strings.Builder
	cmd.Stderr = &stderr
	if err := cmd.Run(); err != nil {
		os.Remove(file)
		return "", fmt.Errorf("mysqldump: %v %s", err, tail(stderr.String(), 3))
	}
	if err := gz.Close(); err != nil {
		return "", err
	}
	return file, nil
}

// Dump writes one database as SQL to w, without CREATE DATABASE / USE, so it can be loaded into a
// database of any name. mode: "full" (default), "structure" (no rows) or "data" (rows only).
func (m MySQL) Dump(rootPassword, name, mode string, w io.Writer) error {
	args := []string{"--socket=" + m.Socket, "--user=root", "--single-transaction", "--routines", "--triggers", "--events",
		"--hex-blob", "--default-character-set=utf8mb4", "--set-gtid-purged=OFF", "--no-tablespaces"}
	switch mode {
	case "structure":
		args = append(args, "--no-data")
	case "data":
		args = append(args, "--no-create-info", "--skip-triggers", "--skip-routines", "--skip-events")
	}
	cmd := exec.Command(m.Bin("mysqldump"), append(args, name)...)
	cmd.Env = append(os.Environ(), "MYSQL_PWD="+rootPassword)
	cmd.Stdout = w
	var stderr strings.Builder
	cmd.Stderr = &stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("mysqldump: %v %s", err, tail(stderr.String(), 3))
	}
	return nil
}

// Restore loads a .sql or .sql.gz file into the server (the dump decides the target database).
func (m MySQL) Restore(rootPassword, file string) error {
	f, err := os.Open(file)
	if err != nil {
		return err
	}
	defer f.Close()
	var r io.Reader = f
	if strings.HasSuffix(file, ".gz") {
		gz, err := gzip.NewReader(f)
		if err != nil {
			return err
		}
		defer gz.Close()
		r = gz
	}
	return m.Import(rootPassword, r, "")
}

// Import pipes SQL into the mysql client. database may be "" when the SQL selects it.
func (m MySQL) Import(rootPassword string, r io.Reader, database string) error {
	args := []string{"--socket=" + m.Socket, "--user=root", "--default-character-set=utf8mb4", "--binary-mode"}
	if database != "" {
		args = append(args, database)
	}
	cmd := exec.Command(m.Bin("mysql"), args...)
	cmd.Env = append(os.Environ(), "MYSQL_PWD="+rootPassword)
	cmd.Stdin = r
	var stderr strings.Builder
	cmd.Stderr = &stderr
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("import: %v %s", err, tail(stderr.String(), 3))
	}
	return nil
}

var ErrNotRunning = errors.New("MySQL is not running")

func tail(s string, n int) string {
	lines := strings.Split(strings.TrimSpace(s), "\n")
	if len(lines) > n {
		lines = lines[len(lines)-n:]
	}
	return strings.Join(lines, " / ")
}
