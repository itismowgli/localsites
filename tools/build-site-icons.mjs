// Builds site/icons.svg: the Lucide icons the website's feature lists use, as one sprite (<use href="icons.svg#i-bell">).
// The same line icons as the app. Run from tools/: node build-site-icons.mjs
import fs from 'node:fs';
import path from 'node:path';

const lucide = path.resolve('node_modules', 'lucide-static', 'icons');
const out = path.resolve('..', 'site', 'icons.svg');
const ICONS = ['wrench', 'shield-check', 'code', 'folder-pen', 'eye', 'file-code', 'key-round', 'database-backup', 'blocks',
  'badge-check', 'eye-off', 'plug', 'git-branch', 'globe', 'stethoscope', 'command', 'bell', 'package', 'hand', 'shield-alert', 'table-2', 'copy-check', 'link-2-off', 'badge-x', 'history', 'combine'];

const symbols = ICONS.map((name) => {
  const src = fs.readFileSync(path.join(lucide, name + '.svg'), 'utf8');
  const inner = src.slice(src.indexOf('>', src.indexOf('<svg')) + 1, src.lastIndexOf('</svg>')).trim().replace(/\s+/g, ' ');
  return `<symbol id="i-${name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">${inner}</symbol>`;
});
const svg = `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Generated by tools/build-site-icons.mjs. Lucide icons (ISC, https://lucide.dev). Do not edit. -->\n${symbols.join('\n')}\n</svg>\n`;
fs.writeFileSync(out, svg);
console.log(`${path.relative(process.cwd(), out)}: ${ICONS.length} icons`);
