const out = {};
for (const [name, file] of Object.entries(ICONS)) {
  const svg = fs.readFileSync(path.join(lucide, file + '.svg'), 'utf8');
  const inner = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s+/g, ' ').trim();
  out[name] = inner;
}
// Brand icons (Simple Icons, CC0): filled 24x24 paths, used for project types and git hosts
const BRANDS = ['laravel', 'nextdotjs', 'php', 'wordpress', 'nodedotjs', 'python', 'github', 'gitlab', 'bitbucket', 'git',
  'react', 'vuedotjs', 'ruby', 'go', 'rust', 'docker', 'mysql', 'postgresql', 'sqlite', 'html5', 'redis', 'django', 'rubyonrails'];
const brands = {};
for (const b of BRANDS) {
  const svg = fs.readFileSync(path.resolve('node_modules', 'simple-icons', 'icons', b + '.svg'), 'utf8');
  brands[b] = (svg.match(/<path d="([^"]+)"/) || [])[1];
}
const js = `/* Generated by tools/build-assets.mjs. Lucide icons (ISC, https://lucide.dev); brand icons from Simple Icons (CC0, https://simpleicons.org). Do not edit. */
window.LS_ICONS = Object.freeze(${JSON.stringify(out)});
window.LS_BRANDS = Object.freeze(${JSON.stringify(brands)});
`;
fs.writeFileSync(path.join(dist, 'icons.js'), js);

fs.mkdirSync(path.join(dist, 'fonts'), { recursive: true });
fs.copyFileSync(path.resolve('node_modules/@fontsource-variable/inter/files/inter-latin-wght-normal.woff2'), path.join(dist, 'fonts', 'inter-latin.woff2'));
fs.writeFileSync(path.join(dist, 'fonts', 'LICENSE-Inter.txt'), 'Inter font by Rasmus Andersson, SIL Open Font License 1.1 — https://rsms.me/inter/\n');
